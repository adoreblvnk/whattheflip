import * as esbuild from "esbuild";
import * as fs from "fs";
import * as path from "path";
import * as zlib from "zlib";

const ROOT_DIR = path.resolve();
const SRC_DIR = path.join(ROOT_DIR, "src");
const DIST_DIR = path.join(ROOT_DIR, "dist");

if (!fs.existsSync(DIST_DIR)) {
  fs.mkdirSync(DIST_DIR, { recursive: true });
}

console.log("==> Building Packet Tracer + Wireshark SD /WWW/ Workbench with VanJS + esbuild...");

// 1. Bundle and minify JavaScript
const jsResult = await esbuild.build({
  entryPoints: [path.join(SRC_DIR, "app.js")],
  bundle: true,
  minify: true,
  format: "iife",
  target: "es2020",
  write: false,
});
const minifiedJs = jsResult.outputFiles[0].text;

// 2. Bundle and minify CSS
const cssResult = await esbuild.build({
  entryPoints: [path.join(SRC_DIR, "style.css")],
  minify: true,
  write: false,
});
const minifiedCss = cssResult.outputFiles[0].text;

// 3. Assemble SD-card /WWW/ assets (INDEX.HTM, APP.JS, STYLE.CSS)
const sdIndexHtml = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width,initial-scale=1.0">
<title>whattheflip // Diagnostic Bench</title>
<link rel="icon" href="data:,">
<link rel="stylesheet" href="/style.css">
</head>
<body>
<div id="app"></div>
<script src="/app.js"></script>
</body>
</html>`;

const WWW_DIR = path.join(DIST_DIR, "WWW");
if (!fs.existsSync(WWW_DIR)) {
  fs.mkdirSync(WWW_DIR, { recursive: true });
}

fs.writeFileSync(path.join(WWW_DIR, "INDEX.HTM"), sdIndexHtml, "utf-8");
fs.writeFileSync(path.join(WWW_DIR, "APP.JS"), minifiedJs, "utf-8");
fs.writeFileSync(path.join(WWW_DIR, "STYLE.CSS"), minifiedCss, "utf-8");

// 4. Gzip compression (level 9 maximum compression)
const gzippedJs   = zlib.gzipSync(Buffer.from(minifiedJs, "utf-8"), { level: 9 });
const gzippedCss  = zlib.gzipSync(Buffer.from(minifiedCss, "utf-8"), { level: 9 });
const indexHtmBuf = Buffer.from(sdIndexHtml, "utf-8");

function formatCArray(name, lenName, buf) {
  let hexBytes = [];
  for (let i = 0; i < buf.length; i++) {
    hexBytes.push("0x" + buf[i].toString(16).padStart(2, "0"));
  }
  let lines = [];
  lines.push(`static const size_t ${lenName} = ${buf.length}U;`);
  lines.push(`static const uint8_t ${name}[] = {`);
  for (let i = 0; i < hexBytes.length; i += 16) {
    lines.push("    " + hexBytes.slice(i, i + 16).join(", ") + ",");
  }
  lines.push("};");
  return lines.join("\n");
}

// 5. Generate C header for MicroSD /WWW/ pre-seeding
let cHeaderLines = [];
cHeaderLines.push("/* Auto-generated by esbuild + gzip pipeline. DO NOT EDIT MANUALLY. */");
cHeaderLines.push("#ifndef DASHBOARD_HTML_H");
cHeaderLines.push("#define DASHBOARD_HTML_H");
cHeaderLines.push("");
cHeaderLines.push("#include <stddef.h>");
cHeaderLines.push("#include <stdint.h>");
cHeaderLines.push("");
cHeaderLines.push(formatCArray("g_www_index_htm", "g_www_index_htm_len", indexHtmBuf));
cHeaderLines.push("");
cHeaderLines.push(formatCArray("g_www_app_js_gz", "g_www_app_js_gz_len", gzippedJs));
cHeaderLines.push("");
cHeaderLines.push(formatCArray("g_www_style_css_gz", "g_www_style_css_gz_len", gzippedCss));
cHeaderLines.push("");
cHeaderLines.push("#endif /* DASHBOARD_HTML_H */");

const mainHeaderPath = path.join(ROOT_DIR, "..", "whattheflip", "main", "dashboard_html.h");
fs.writeFileSync(mainHeaderPath, cHeaderLines.join("\n"), "utf-8");

console.log(`[SUCCESS] SD /WWW/ Pre-Seed Bundle generated:`);
console.log(`  - SD /WWW/INDEX.HTM : ${indexHtmBuf.length} B`);
console.log(`  - SD /WWW/APP.JS    : ${minifiedJs.length} B (gzipped: ${gzippedJs.length} B)`);
console.log(`  - SD /WWW/STYLE.CSS : ${minifiedCss.length} B (gzipped: ${gzippedCss.length} B)`);
console.log(`  - Firmware Header   : ${mainHeaderPath}`);
