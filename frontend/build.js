import * as esbuild from "esbuild";
import * as fs from "fs";
import * as path from "path";
import * as zlib from "zlib";

const ROOT_DIR = path.resolve();
const SRC_DIR = path.join(ROOT_DIR, "src");
const DIST_DIR = path.join(ROOT_DIR, "dist");

if (!fs.existsSync(DIST_DIR)) {
  fs.mkdirSync(DIST_DIR, { recursive: true });
}

console.log("==> Building Technical Editorial Dashboard with VanJS + esbuild...");

// 1. Bundle and minify JavaScript
const jsResult = await esbuild.build({
  entryPoints: [path.join(SRC_DIR, "app.js")],
  bundle: true,
  minify: true,
  format: "iife",
  target: "es2020",
  write: false,
});
const minifiedJs = jsResult.outputFiles[0].text;

// 2. Bundle and minify CSS
const cssResult = await esbuild.build({
  entryPoints: [path.join(SRC_DIR, "style.css")],
  minify: true,
  write: false,
});
const minifiedCss = cssResult.outputFiles[0].text;

// 3. Assemble single self-contained standalone index.html
const htmlContent = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width,initial-scale=1.0">
<title>whattheflip // Diagnostic Bench</title>
<style>${minifiedCss}</style>
</head>
<body>
<div id="app"></div>
<script>${minifiedJs}</script>
</body>
</html>`;

const distHtmlPath = path.join(DIST_DIR, "index.html");
fs.writeFileSync(distHtmlPath, htmlContent, "utf-8");

// 4. Gzip compression (level 9 maximum compression)
const gzipped = zlib.gzipSync(Buffer.from(htmlContent, "utf-8"), { level: 9 });
const distGzPath = path.join(DIST_DIR, "index.html.gz");
fs.writeFileSync(distGzPath, gzipped);

// 5. Generate C header for direct embedding into ESP32-C6 / whattheflip firmware
let hexBytes = [];
for (let i = 0; i < gzipped.length; i++) {
  hexBytes.push("0x" + gzipped[i].toString(16).padStart(2, "0"));
}

let cHeaderLines = [];
cHeaderLines.push("/* Auto-generated by esbuild + gzip pipeline. DO NOT EDIT MANUALLY. */");
cHeaderLines.push("#ifndef DASHBOARD_HTML_H");
cHeaderLines.push("#define DASHBOARD_HTML_H");
cHeaderLines.push("");
cHeaderLines.push("#include <stddef.h>");
cHeaderLines.push("#include <stdint.h>");

cHeaderLines.push("");
cHeaderLines.push(`static const size_t g_dashboard_html_gz_len = ${gzipped.length}U;`);
cHeaderLines.push("static const uint8_t g_dashboard_html_gz[] = {");
for (let i = 0; i < hexBytes.length; i += 16) {
  cHeaderLines.push("    " + hexBytes.slice(i, i + 16).join(", ") + ",");
}
cHeaderLines.push("};");
cHeaderLines.push("");
cHeaderLines.push("#endif /* DASHBOARD_HTML_H */");

const mainHeaderPath = path.join(ROOT_DIR, "..", "whattheflip", "main", "dashboard_html.h");
fs.writeFileSync(mainHeaderPath, cHeaderLines.join("\n"), "utf-8");
const cHeaderPath = path.join(DIST_DIR, "dashboard_html.h");
fs.writeFileSync(cHeaderPath, cHeaderLines.join("\n"), "utf-8");

const rawSizeKb = (Buffer.byteLength(htmlContent, "utf-8") / 1024).toFixed(2);
const gzSizeKb = (gzipped.length / 1024).toFixed(2);

console.log(`[SUCCESS] Bundle generated:`);
console.log(`  - Standalone HTML : ${distHtmlPath} (${rawSizeKb} KB)`);
console.log(`  - Gzipped HTML    : ${distGzPath} (${gzSizeKb} KB)`);
console.log(`  - Firmware Header : ${cHeaderPath} (${gzipped.length} bytes in flash)`);
